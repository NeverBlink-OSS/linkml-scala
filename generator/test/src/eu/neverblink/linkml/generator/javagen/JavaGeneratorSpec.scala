    "generate every inline form" in {
      val files = generate(
        """classes:
          |  Container:
          |    attributes:
          |      one: {range: Thing, inlined: true}
          |      list: {range: Thing, multivalued: true, inlined_as_list: true}
          |      dict: {range: Thing, multivalued: true, inlined: true}
          |      simple: {range: Tag, multivalued: true, inlined: true}
          |      ref: {range: Thing}
          |      refs: {range: Thing, multivalued: true}
          |  Thing:
          |    attributes:
          |      id: {identifier: true}
          |      name:
          |      count: {range: integer}
          |  Tag:
          |    attributes:
          |      key: {key: true, range: integer}
          |      label:
          |""".stripMargin,
      )
      val code = files("Container.java")
      code should include("    private Thing one;")
      code should include("    private List<Thing> list;")
      code should include("    private Map<String, Thing> dict;")
      code should include("    private Map<String, Tag> simple;")
      code should include("    private String ref;")
      code should include("    /** Reference to Thing */\n    public String getRef() {")
      code should include("    private List<String> refs;")
      code should include(
        "LinkMLJson.withKeys(dict, Thing::new, k -> k, Thing::getId, " +
          "Thing::setId, \"id\")",
      )
      code should include(
        "    @JsonGetter(\"dict\")\n    @JsonIgnoreProperties(value = \"id\", allowSetters = true)",
      )
      code should include("return LinkMLJson.keyed(dict, null);")
      code should include("LinkMLJson::integerKey, Tag::getKey, Tag::setKey, \"key\")")
      code should include("return LinkMLJson.keyed(simple, Tag::json$bare);")
      // A dict leaves the key out of its objects, so it is not required there
      files("Thing.java") should include("@JsonProperty(\"id\") String id,")
      // A simple dict entry may be just the value
      val tag = files("Tag.java")
      tag should include(
        "    @JsonCreator(mode = JsonCreator.Mode.DELEGATING)\n" +
          "    private static Tag json$of(String value) {",
      )
      tag should include("    Object json$bare() {\n        return getLabel();\n    }")
    }

    "generate type designators as Jackson subtypes" in {
      val files = generate(
        """classes:
          |  Animal:
          |    abstract: true
          |    attributes:
          |      kind:
          |        designates_type: true
          |        required: true
          |      name:
          |  Lion:
          |    is_a: Animal
          |  Parrot:
          |    is_a: Animal
          |  Zoo:
          |    attributes:
          |      animals: {range: Animal, multivalued: true, inlined_as_list: true}
          |""".stripMargin,
      )
      val animal = files("Animal.java")
      animal should include("public abstract class Animal {")
      animal should include(
        """@JsonTypeInfo(
          |    use = JsonTypeInfo.Id.NAME,
          |    include = JsonTypeInfo.As.EXISTING_PROPERTY,
          |    property = "kind",
          |    visible = true)
          |@JsonSubTypes({
          |    @JsonSubTypes.Type(value = Lion.class, name = "Lion"),
          |    @JsonSubTypes.Type(value = Parrot.class, name = "Parrot"),
