      )
      // Jackson makes instances of the subclasses only
      animal should not include "json$create"
      val lion = files("Lion.java")
      lion should include("public class Lion extends Animal {")
      lion should include("    public Lion() {\n        setKind(\"Lion\");\n    }")
      lion should include("@JsonProperty(value = \"kind\", required = true) String kind,")
      files("Zoo.java") should include("    private List<Animal> animals;")
    }

