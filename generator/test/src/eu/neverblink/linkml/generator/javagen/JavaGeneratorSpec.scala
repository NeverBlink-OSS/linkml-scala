package eu.neverblink.linkml.generator.javagen

import eu.neverblink.linkml.generator.options.{JavaGeneratorOptions, PruningMode}
import eu.neverblink.linkml.schemaview.{SchemaIssues, SchemaView}
import eu.neverblink.linkml.tests.ModelCatalogue
import org.scalatest.matchers.should.Matchers
import org.scalatest.wordspec.AnyWordSpec

class JavaGeneratorSpec extends AnyWordSpec, Matchers {
  def load(classesYaml: String): SchemaView =
    SchemaIssues.orThrow(
      SchemaView.loadSchemaViewFromString(
        s"""id: https://neverblink.eu/linkml/java/test/
           |name: test
           |prefixes:
           |  ex: https://neverblink.eu/linkml/java/test/
           |default_prefix: ex
           |imports:
           |  - linkml:types
           |$classesYaml""".stripMargin,
      ),
    )

  def generate(
      classesYaml: String,
      options: JavaGeneratorOptions = JavaGeneratorOptions(),
  ): Map[String, String] =
    JavaGenerator(using load(classesYaml)).generate(options).toMap

  /** One generated file, by the name of its type. */
  def file(
      classesYaml: String,
      name: String,
      options: JavaGeneratorOptions = JavaGeneratorOptions(),
  ): String =
    generate(classesYaml, options)(s"$name.java")

  "JavaGenerator" should {
    "write one file per class and enum, in the schema's package" in {
      val files = generate(
        """classes:
          |  A:
          |  B:
          |enums:
          |  E:
          |    permissible_values:
          |      x:
          |""".stripMargin,
      )
      // Nothing needs the helper class, so there is none
      files.keySet shouldBe Set("A.java", "B.java", "E.java")
      files.values.foreach { code =>
        code should startWith(
          "// Generated by ohi LinkML from https://neverblink.eu/linkml/java/test/",
        )
        code should include("\npackage test;\n")
      }
      generate("classes:\n  A:\n", JavaGeneratorOptions(`package` = Some("org.example")))(
        "A.java",
      ) should
        include("\npackage org.example;\n")
    }

    "give every function of a catalogue model a method on one interface" in {
      ModelCatalogue.all.filter(_.model.root.functions.nonEmpty).foreach { entry =>
        withClue(s"${entry.name}: ") {
          val files = JavaGenerator(using entry.model).generate().toMap
          val name = JavaRenamer.functionsInterfaceName(entry.model)
          files(s"$name.java") should include(s"public interface $name {")
          entry.model.root.functions.keys.foreach { fn =>
            val fv = entry.model.functions(fn)
            files(s"$name.java") should include(s" ${JavaRenamer.functionName(fv)}(")
            fv.errors.foreach { cls =>
              val error = JavaRenamer.errorName(cls)
              files(s"$error.java") should include(s"public class $error extends Exception {")
              files(s"$name.java") should include(s"@throws $error ")
            }
          }
        }
      }
    }

    "throw the errors of a function rather than returning them" in {
      val files = JavaGenerator(using ModelCatalogue.functions.returns.model).generate().toMap
      files("ClosedError.java") should include("    public ClosedError(Closed error) {")
      files("ClosedError.java") should include("    public Closed getError() {")
      val functions = files.collectFirst { case (n, c) if n.endsWith("Functions.java") => c }.get
      functions should include("Item fetch(String id) throws UnavailableError, ClosedError;")
      functions should include("@throws ClosedError The store is closed.")
      functions should include("Status status();") // an enum
      val basic = JavaGenerator(using ModelCatalogue.functions.basic.model).generate().toMap
        .collectFirst { case (n, c) if n.endsWith("Functions.java") => c }.get
      basic should include("void reindex();")
      basic should include("void remove(String title) throws NotFoundError;")
    }

    "map slot ranges to Java types" in {
      val code = file(
        """classes:
          |  Anything:
          |    class_uri: linkml:Any
          |  C:
          |    attributes:
          |      s: {range: string, required: true}
          |      i: {range: integer}
          |      f: {range: float}
          |      d: {range: decimal}
          |      b: {range: boolean}
          |      day: {range: date}
          |      when: {range: datetime}
          |      at: {range: time}
          |      u: {range: uri}
          |      uc: {range: uriorcurie}
          |      many: {range: string, multivalued: true}
          |      whatever: {range: Anything}
          |      title: {range: langstring}
          |""".stripMargin,
        "C",
      )
      Seq(
        "    private String s;",
        "    private Long i;",
        "    private Double f;",
        "    private BigDecimal d;",
        "    private Boolean b;",
        "    private LocalDate day;",
        "    private OffsetDateTime when;",
        "    private OffsetTime at;",
        "    private String u;",
        "    private String uc;",
        "    private List<String> many;",
        "    private Object whatever;",
        "    private Object title;",
      ).foreach(snippet => code should include(snippet))
      code should include("    public Long getI() {")
      code should include("    public void setI(Long i) {")
      // Jackson reads them, and checks that the required ones are there
      code should include("@JsonProperty(\"i\") Long i,")
      code should include("json$item.setI(i);")
      code should include("@JsonProperty(value = \"s\", required = true) String s,")
      code should include(
        "@JsonProperty(\"many\") @JsonSetter(contentNulls = Nulls.FAIL) List<String> many,",
      )
      // Dates and times are read and written as text, which Jackson 2 can't do on its own
      code should include("json$item.setDay(LinkMLJson.date(day));")
      code should include("    @JsonGetter(\"day\")\n    private Object json$day() {")
      code should include("return LinkMLJson.jsonDate(day);")
    }

    "read every value itself when strict, so that Jackson doesn't convert them" in {
      val code = file(
        """classes:
          |  C:
          |    attributes:
          |      s: {range: string, required: true}
          |      i: {range: integer}
          |      many: {range: string, multivalued: true}
          |      title: {range: langstring}
          |""".stripMargin,
        "C",
        JavaGeneratorOptions(strict = true),
      )
      code should include(
        "@JsonProperty(value = \"s\", required = true) @JsonSetter(nulls = Nulls.FAIL) Object s,",
      )
      code should include("json$item.setS(LinkMLJson.string(s));")
      code should include("json$item.setI(LinkMLJson.integer(i));")
      code should include("json$item.setMany(LinkMLJson.list(many, LinkMLJson::string));")
      code should include("json$item.setTitle(LinkMLJson.text(title));")
    }

    "include only the helper methods that the classes use" in {
      val schema =
        """classes:
          |  C:
          |    attributes:
          |      day: {range: date}
          |      i: {range: integer}
          |""".stripMargin
      val helper = generate(schema)("LinkMLJson.java")
      helper should include("final class LinkMLJson {")
      helper should include("    static LocalDate date(Object value) {")
      helper should include("    static String jsonDate(LocalDate value) {")
      // used by date()
      helper should include("    private static IllegalArgumentException expected(")
      helper should include("import java.time.LocalDate;")
      helper should not include "integer("
      helper should not include "withKeys"
      helper should not include "OffsetDateTime"
      val strict = generate(schema, JavaGeneratorOptions(strict = true))("LinkMLJson.java")
      strict should include("    static Long integer(Object value) {")
      strict should include("import java.math.BigInteger;")
    }

    "import only what the file uses" in {
      val code = file(
        """classes:
          |  C:
          |    attributes:
          |      s: {range: string}
          |""".stripMargin,
        "C",
      )
      code should include("import com.fasterxml.jackson.annotation.JsonProperty;\n")
      code should include("import java.util.Objects;\n")
      code should not include "java.time"
      code should not include "java.math"
      code should not include "import java.util.List;"
      code should not include "JsonTypeInfo"
      code should not include "databind"
    }

    "check what the schema says beyond the types while reading" in {
      val code = file(
        """types:
          |  Code:
          |    typeof: string
          |    pattern: "^[A-Z]+$"
          |classes:
          |  C:
          |    attributes:
          |      age: {range: integer, minimum_value: 0, maximum_value: 200}
          |      codes: {range: Code, multivalued: true, minimum_cardinality: 1, maximum_cardinality: 3}
          |      quote: {range: string, pattern: 'say "hi"'}
          |      price: {range: decimal, minimum_value: 0.5}
          |      code: {range: string, minimum_length: 2, maximum_length: 5}
          |      title: {range: langstring, maximum_length: 5}
          |      named: {range: string, pattern: "^(?P<word>\\w+)$"}
          |""".stripMargin,
        "C",
        JavaGeneratorOptions(strict = true),
      )
      code should include("LinkMLJson.between(LinkMLJson.integer(age), \"0\", \"200\", \"age\")")
      code should include(
        "LinkMLJson.count(LinkMLJson.list(codes, v -> LinkMLJson.checkText(LinkMLJson.string(v), -1, " +
          "-1, json$codesPattern, \"codes\")), 1, 3, \"codes\")",
      )
      code should include("Pattern.compile(\"^[A-Z]+$\")")
      code should include("Pattern.compile(\"say \\\"hi\\\"\")")
      code should include("LinkMLJson.between(price, \"0.5\", null, \"price\")")
      code should include("LinkMLJson.checkText(LinkMLJson.string(code), 2, 5, null, \"code\")")
      code should include("LinkMLJson.checkText(LinkMLJson.text(title), -1, 5, null, \"title\")")
      // Python's named groups, in Java's syntax
      code should include("Pattern.compile(\"^(?<word>\\\\w+)$\")")
      // Not without strict
      val lenient = file(
        "classes:\n  C:\n    attributes:\n      age: {range: integer, minimum_value: 0}\n",
        "C",
      )
      lenient should include("json$item.setAge(age);")
    }

