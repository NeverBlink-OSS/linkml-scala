    "prune with each pruning mode, keeping the parents" when {
      val schema =
        """classes:
          |  Container:
          |    tree_root: true
          |    attributes:
          |      things: {range: Special, multivalued: true, inlined_as_list: true}
          |  Base:
          |    attributes:
          |      x: {range: integer}
          |  Special:
          |    is_a: Base
          |  Unrelated:
          |    attributes:
          |      x: {range: integer}
          |enums:
          |  Unused:
          |    permissible_values:
          |      a:
          |""".stripMargin

      "skip, by default: everything" in {
        val files = generate(schema)
        files.keySet should contain allOf ("Unrelated.java", "Unused.java")
      }

      "treeRoot: what the tree root reaches, and their parents" in {
        val files = generate(schema, JavaGeneratorOptions(pruningMode = PruningMode.TreeRoot))
        files.keySet shouldBe Set("Container.java", "Special.java", "Base.java")
        files("Special.java") should include("public class Special extends Base {")
      }
    }

    "reject unknown properties, unless the class is open" in {
      val schema =
        """classes:
          |  Closed:
          |    attributes:
          |      a:
          |  Open:
          |    extra_slots:
          |      allowed: true
          |    attributes:
          |      a:
          |  ClosedAgain:
          |    is_a: Open
          |""".stripMargin
      val files = generate(schema)
      files("Closed.java") should include(
        "    @JsonAnySetter\n    protected void json$extra(String key, Object value) {\n" +
          "        throw new IllegalArgumentException(\"unknown property \\\"\" + key + \"\\\"\");",
      )
      val open = files("Open.java")
      open should include(
        "    private final Map<String, Object> extraProperties = new LinkedHashMap<>();",
      )
      open should include("extraProperties.put(key, value);")
      open should include("    public Map<String, Object> getExtraProperties() {")
      // extra_slots is not inherited
      files("ClosedAgain.java") should include(
        "    @Override\n    @JsonAnySetter\n    protected void json$extra(String key, Object value) {\n" +
          "        throw new IllegalArgumentException(\"unknown property \\\"\" + key + \"\\\"\");",
      )
      val all = generate(schema, JavaGeneratorOptions(open = true))
      all("Closed.java") should include("extraProperties.put(key, value);")
      all("ClosedAgain.java") should not include "json$extra"
    }

