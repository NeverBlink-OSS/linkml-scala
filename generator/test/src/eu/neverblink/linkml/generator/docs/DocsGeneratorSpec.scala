package eu.neverblink.linkml.generator.docs

import eu.neverblink.linkml.generator.erdiagram.ErDiagramGenerator
import eu.neverblink.linkml.generator.pydantic.PydanticGenerator
import eu.neverblink.linkml.generator.util.PruningMode
import eu.neverblink.linkml.schemaview.{ElementView, SchemaIssues, SchemaView}
import eu.neverblink.linkml.tests.ModelCatalogue
import org.scalatest.matchers.should.Matchers
import org.scalatest.wordspec.AnyWordSpec

class DocsGeneratorSpec extends AnyWordSpec, Matchers {

  /** Load a self-contained schema, for the cases the model catalogue does not cover. */
  private def schemaOf(body: String): SchemaView =
    SchemaIssues.orThrow(
      SchemaView.loadSchemaViewFromString(
        s"""id: https://neverblink.eu/test/
           |name: test
           |default_range: string
           |types:
           |  string:
           |    base: str
           |$body
           |""".stripMargin,
      ),
    )

  /** The generated files of [[sv]], keyed by path. */
  private def files(
      sv: SchemaView,
      options: DocsGenerator.Options = DocsGenerator.Options(),
  ): Map[String, String] =
    DocsGenerator(using sv).generateFiles(options).map(_.toTuple).toMap

  "DocsGenerator.generateFiles" should {
    "write an index plus a page for each class, slot, enum and type in its own folder" in {
      val result = files(ModelCatalogue.`enum`.model)
      result.keySet shouldBe Set(
        "index.md",
        "classes/SomeClass.md",
        "enums/SomeEnum.md",
        "types/string.md",
      )
    }

    "name the path and the content of each file" in {
      val index = DocsGenerator(using ModelCatalogue.inheritance.model).generateFiles().head
      index.path shouldBe "index.md"
      index.content should startWith("<!-- Generated by LinkML-Scala from ")
      DocsSite.PageKind.values.map(_.dir).toSeq shouldBe Seq("classes", "slots", "enums", "types")
    }

    "start every page with the generated header" in {
      files(ModelCatalogue.inheritance.model).values.foreach { page =>
        page should startWith(
          "<!-- Generated by LinkML-Scala from https://neverblink.eu/linkml/tests/inheritance/. " +
            "DO NOT EDIT. -->\n",
        )
      }
    }

    "describe the schema and list its elements on the index page" in {
      val index = files(ModelCatalogue.inheritance.model)("index.md")
      index should include("# inheritance\n")
      index should include("- **Tree root:** [ChildClass](classes/ChildClass.md)\n")
      index should include("| [BaseClass](classes/BaseClass.md) |  |\n")
      index should include("| [some_slot](slots/some_slot.md) |  |\n")
      index should include("| [string](types/string.md) | A character string |\n")
    }

    "list the slots of a class, with their ranges, cardinalities and where they come from" in {
      val page = files(ModelCatalogue.inheritance.model)("classes/ChildClass.md")
      page should include("# Class: ChildClass\n")
      page should include("- **Parent:** [BaseClass](BaseClass.md)\n")
      page should include("- **Tree root:** yes\n")
      page should include(
        """| Name | Range | Cardinality | Description | Inherited from |
          || --- | --- | --- | --- | --- |
          || [some_slot](../slots/some_slot.md) | [string](../types/string.md) | 0..1 |  |  |
          || [some_other_slot](../slots/some_other_slot.md) | [integer](../types/integer.md) | 1 |  | [BaseClass](BaseClass.md) |
          || [yet_another_slot](../slots/yet_another_slot.md) | [BaseRefClass](BaseRefClass.md) (reference) | 1 |  |  |
          |""".stripMargin,
      )
    }

    "show the inheritance of a class as a nested list" in {
      // Each level is indented by 4 spaces, as MkDocs needs. GitHub and other CommonMark tools
      // read it the same way as 2 spaces.
      val pages = files(ModelCatalogue.inheritance.model)
      pages("classes/ChildClass.md") should include(
        """## Inheritance
          |
          |- [BaseClass](BaseClass.md)
          |    - **ChildClass**
          |""".stripMargin,
      )
      pages("classes/BaseClass.md") should include(
        """- **BaseClass**
          |    - [ChildClass](ChildClass.md)
          |""".stripMargin,
      )
    }

    "mark identifiers and keep attributes without a slot page unlinked" in {
      val page = files(ModelCatalogue.inheritance.model)("classes/BaseRefClass.md")
      page should include("| id (identifier) | [string](../types/string.md) | 1 |  |  |\n")
    }

    "list the slots that use a class as their range" in {
      val page = files(ModelCatalogue.inheritance.model)("classes/BaseRefClass.md")
      page should include(
        """## Usages
          |
          || Used by | Slot | Cardinality |
          || --- | --- | --- |
          || [ChildClass](ChildClass.md) | [yet_another_slot](../slots/yet_another_slot.md) | 1 |
          |""".stripMargin,
      )
    }

    "add the sections of a subclass at the end of the pages" in {
      val sv = ModelCatalogue.inheritance.model
      val generator = new DocsGenerator(using sv) {
        override protected def indexSections(md: Markdown, site: DocsSite): Unit = {
          md.heading(2, "Diagram")
          md.codeBlock(
            "mermaid",
            ErDiagramGenerator(using sv).serialize(ErDiagramGenerator.Options()),
          )
        }

        override protected def elementSections(
            md: Markdown,
            el: ElementView[?, ?],
            site: DocsSite,
        ): Unit = {
          md.startHeading(2)
          md.text("Notes on " + el.name)
          md.endBlock()
        }
      }
      val pages = generator.generateFiles().map(_.toTuple).toMap
      pages("index.md") should include("## Diagram\n\n```mermaid\n")
      pages("index.md") should include("erDiagram\n")
      pages("classes/ChildClass.md") should endWith("## Notes on ChildClass\n\n")
      // In one document, the pages are sections, so their headings are one level lower.
      val document = generator.serialize()
      document should include("## Diagram\n\n```mermaid\n")
      document should include("### Notes on ChildClass\n\n")
    }

    "list the classes that have a slot on the slot's page" in {
      val page = files(ModelCatalogue.inheritance.model)("slots/some_other_slot.md")
      page should include("# Slot: some_other_slot\n")
      page should include("- **Range:** [integer](../types/integer.md)\n")
      page should include("- **Cardinality:** 1\n")
      page should include(
        "| [BaseClass](../classes/BaseClass.md) | [integer](../types/integer.md) | 1 |\n",
      )
      // ChildClass inherits the slot unchanged, so it is not listed again.
      page should not include "ChildClass"
    }

    "list the permissible values of an enum with their meanings" in {
      val page = files(ModelCatalogue.`enum`.model)("enums/SomeEnum.md")
      page should include(
        """| Value | Meaning | Description |
          || --- | --- | --- |
          || `SOME_OPTION` | [`ex:some_option`](https://example.org/some_option) |  |
          || `SOME_OTHER_OPTION` |  |  |
          || `YET_ANOTHER_OPTION` |  |  |
          |""".stripMargin,
      )
      page should include("| [SomeClass](../classes/SomeClass.md) | some_slot | 0..1 |\n")
    }

    "say when an enum has no fixed list of values" in {
      files(ModelCatalogue.emptyEnum.model).collect {
        case (path, page) if path.startsWith("enums/") => page
      }.foreach(_ should include("This enum has no fixed list of values."))
    }

    "say where the values of an enum come from" in {
      val sv = schemaOf(
        """prefixes:
          |  NCBITaxon: http://purl.obolibrary.org/obo/NCBITaxon_
          |enums:
          |  Base:
          |    permissible_values:
          |      a:
          |  Derived:
          |    inherits: [Base]
          |    include:
          |      - permissible_values:
          |          b:
          |    minus:
          |      - permissible_values:
          |          a:
          |  Species:
          |    reachable_from:
          |      source_nodes: [NCBITaxon:9606]
          |      is_direct: true
          |      include_self: true
          |""".stripMargin,
      )
      val pages = files(sv, DocsGenerator.Options(pruningMode = PruningMode.skip))
      pages("enums/Derived.md") should include(
        """## Values from
          |
          |- **Inherits:** [Base](Base.md)
          |- **Includes:** values `b`
          |- **Excludes:** values `a`
          |
          |## Permissible values
          |
          |The values come from the sources above, so they aren't listed here.
          |""".stripMargin,
      )
      pages("enums/Species.md") should include(
        """## Values from
          |
          |- **Source nodes:** [`NCBITaxon:9606`](http://purl.obolibrary.org/obo/NCBITaxon_9606)
          |- **Direct only:** yes
          |- **Includes the source nodes:** yes
          |""".stripMargin,
      )
    }

    "link mixins in both directions" in {
      val pages = files(ModelCatalogue.mixin.model)
      pages("classes/SomeClass.md") should include(
        "- **Mixins:** [SomeOtherClass](SomeOtherClass.md)\n",
      )
      pages("classes/SomeOtherClass.md") should include(
        "- **Mixed into:** [SomeClass](SomeClass.md)\n",
      )
      pages("classes/SomeOtherClass.md") should include("- **Mixin:** yes")
    }

    "show each range of an any_of" in {
      val page = files(ModelCatalogue.unionRange.model)("classes/Union.md")
      page should include("[integer](../types/integer.md) or [string](../types/string.md)")
    }

    "show each range of an exactly_one_of or all_of" in {
      val sv = schemaOf(
        """classes:
          |  Cat: {}
          |  Dog: {}
          |  Owner:
          |    slots: [pet, buddy]
          |slots:
          |  pet:
          |    exactly_one_of:
          |      - range: Cat
          |      - range: Dog
          |  buddy:
          |    all_of:
          |      - range: Cat
          |      - range: Dog
          |""".stripMargin,
      )
      val pages = files(sv)
      pages("slots/pet.md") should include(
        "- **Range:** exactly one of [Cat](../classes/Cat.md), [Dog](../classes/Dog.md)\n",
      )
      pages("slots/buddy.md") should include(
        "- **Range:** all of [Cat](../classes/Cat.md), [Dog](../classes/Dog.md)\n",
      )
      pages("classes/Owner.md") should include(
        "| [pet](../slots/pet.md) | exactly one of [Cat](Cat.md), [Dog](Dog.md) |",
      )
      pages("classes/Dog.md") should include("| [Owner](Owner.md) | [pet](../slots/pet.md) |")
      pages("classes/Dog.md") should include("| [Owner](Owner.md) | [buddy](../slots/buddy.md) |")
    }

    "list the unique keys of a class" in {
      val sv = schemaOf(
        """classes:
          |  Person:
          |    slots: [email]
          |    attributes:
          |      name:
          |    unique_keys:
          |      contact:
          |        unique_key_slots: [name, email]
          |        description: No two people share a name and an email.
          |        consider_nulls_inequal: true
          |slots:
          |  email:
          |""".stripMargin,
      )
      files(sv)("classes/Person.md") should include(
        """## Unique keys
          |
          || Name | Slots | Description |
          || --- | --- | --- |
          || contact | name, [email](../slots/email.md) | No two people share a name and an email. Missing values never match. |
          |""".stripMargin,
      )
    }

    "say that a class has rules, which the page doesn't show" in {
      val sv = schemaOf(
        """classes:
          |  Person:
          |    attributes:
          |      age:
          |    rules:
          |      - preconditions:
          |          slot_conditions:
          |            age:
          |              equals_string: "0"
          |        postconditions:
          |          slot_conditions:
          |            age:
          |              required: true
          |""".stripMargin,
      )
      files(sv)("classes/Person.md") should include(
        "- **Rules:** 1, not shown here. See the schema.\n",
      )
    }

    "show cardinalities" in {
      val page = files(ModelCatalogue.cardinality.model).collectFirst {
        case (path, page) if path.startsWith("classes/") => page
      }.get
      Seq("| 1 |", "| 0..1 |", "| 1..* |", "| 0..* |").foreach(page should include(_))
    }

    "show explicit cardinalities" in {
      val page = files(ModelCatalogue.cardinalityExplicit.model)("classes/Cardinal.md")
      page should include(
        "| [exactly_two](../slots/exactly_two.md) | [string](../types/string.md) | 2 |",
      )
      page should include(
        "| [one_to_three](../slots/one_to_three.md) | [string](../types/string.md) | 1..3 |",
      )
    }

    "show the constraints of a slot" in {
      val sv = schemaOf(
        """classes:
          |  Person:
          |    slots: [code, friends]
          |slots:
          |  code:
          |    equals_string: X|Y
          |    minimum_length: 2
          |    maximum_length: 8
          |    recommended: true
          |  friends:
          |    range: Person
          |    multivalued: true
          |    inlined_as_list: true
          |""".stripMargin,
      )
      val pages = files(sv)
      pages("slots/code.md") should include(
        """- **Recommended:** yes
          |- **Equals:** `X|Y`
          |- **Minimum length:** 2
          |- **Maximum length:** 8
          |""".stripMargin,
      )
      pages("slots/friends.md") should include("- **Inlined:** yes, as a list\n")
    }

    "show the parent and the constraints of a type" in {
      val page = files(ModelCatalogue.typeDerivation.model)("types/Code.md")
      page should include("- **Parent:** [string](string.md)\n")
      page should include("- **Pattern:** `^[A-Z]{3}$`\n")
    }

    "document only the classes reachable from the tree root in tree root mode" in {
      val sv = schemaOf(
        """classes:
          |  Root:
          |    tree_root: true
          |    attributes:
          |      child:
          |        range: Child
          |  Child:
          |  Unused:
          |""".stripMargin,
      )
      files(sv, DocsGenerator.Options(pruningMode = PruningMode.treeRoot(None))).keySet
        .filter(_.startsWith("classes/")) shouldBe Set("classes/Root.md", "classes/Child.md")
      files(sv, DocsGenerator.Options(pruningMode = PruningMode.skip)).keySet should contain(
        "classes/Unused.md",
      )
    }

    "give elements whose names differ only in case their own files" in {
      val sv = schemaOf(
        """classes:
          |  Person:
          |  person:
          |""".stripMargin,
      )
      val pages = files(sv)
      pages.keySet should contain allOf ("classes/Person.md", "classes/person_2.md")
      pages("index.md") should include("[person](classes/person_2.md)")
      pages("classes/person_2.md") should include("- **Canonical name:** `Person`\n")
    }

    "show the other names of an element" in {
      val sv = schemaOf(
        """classes:
          |  natural person:
          |    title: Natural person
          |    aliases: [human, individual]
          |    slots: [birth date]
          |    attributes:
          |      type:
          |slots:
          |  birth date:
          |    alias: birthDate
          |enums:
          |  Gender:
          |    permissible_values:
          |      female:
          |        alias: F
          |        title: Female
          |        description: A woman or a girl.
          |""".stripMargin,
      )
      val pages = files(sv, DocsGenerator.Options(pruningMode = PruningMode.skip))
      pages("classes/natural_person.md") should include(
        """# Class: natural person
          |
          |- **Title:** Natural person
          |- **Canonical name:** `NaturalPerson`
          |- **Other names:** human, individual
          |- **Names in code:** `NaturalPerson` (Scala, TypeScript, Python, GraphQL)
          |- **URI:**""".stripMargin,
      )
      pages("classes/natural_person.md") should include(
        "| [birth date](../slots/birth_date.md) (`birthDate` in data) |",
      )
      pages("classes/natural_person.md") should include("| type |")
      pages("slots/birth_date.md") should include(
        """# Slot: birth date
          |
          |- **Canonical name:** `birth_date`
          |- **Name in data:** `birthDate`
          |- **Names in code:** `birthDate` (Scala, TypeScript, Python), `birth_date` (GraphQL)
          |""".stripMargin,
      )
      pages("enums/Gender.md") should include(
        "| `female` (`F` in data) |  | **Female**: A woman or a girl. |\n",
      )
      // All the names are the same, so there is nothing more to show.
      pages("enums/Gender.md") should include("# Enum: Gender\n\n- **URI:**")
    }

    "show only the names that the code generators give" in {
      val sv = schemaOf(
        """classes:
          |  Container:
          |    tree_root: true
          |    slots: [ContainerDocument]
          |slots:
          |  ContainerDocument:
          |    range: status_kind
          |enums:
          |  status_kind: {}
          |""".stripMargin,
      )
      val pages = files(sv)
      // The Python generator names the document type of the tree root `ContainerDocument`, so it
      // renames the field
      pages("slots/ContainerDocument.md") should include(
        "- **Names in code:** `containerDocument` (Scala), `ContainerDocument` (TypeScript), " +
          "`ContainerDocument_` (Python), `container_document` (GraphQL)\n",
      )
      PydanticGenerator(using sv).serialize() should include("    ContainerDocument_: ")
      // An enum without values is a string in Scala and Python, so only TypeScript and GraphQL
      // have a type with its name
      pages("enums/status_kind.md") should include(
        "- **Names in code:** `StatusKind` (TypeScript, GraphQL)\n",
      )
    }

    "escape names and keep descriptions on one line in tables" in {
      val sv = schemaOf(
        """classes:
          |  Root:
          |    description: |-
          |      Holds *things* | stuff.
          |      More on the next line.
          |
          |      A second paragraph.
          |    attributes:
          |      _private_:
          |""".stripMargin,
      )
      val pages = files(sv)
      pages("index.md") should include(
        "| [Root](classes/Root.md) | Holds *things* \\| stuff. More on the next line. |\n",
      )
      // The page itself keeps the whole description.
      pages("classes/Root.md") should include(
        "Holds *things* | stuff.\nMore on the next line.\n\nA second paragraph.\n",
      )
      pages("classes/Root.md") should include("| \\_private\\_ |")
    }

    "show deprecation notices" in {
      val sv = schemaOf(
        """classes:
          |  Old:
          |    deprecated: Use New instead.
          |""".stripMargin,
      )
      files(sv)("classes/Old.md") should include("> **Deprecated:** Use New instead.\n")
    }

    "write descriptions in the requested language" in {
      val sv = schemaOf(
        """classes:
          |  Thing:
          |    description:
          |      en: A thing.
          |      de: Ein Ding.
          |""".stripMargin,
      )
      files(sv, DocsGenerator.Options(metadataLanguage = "de"))("classes/Thing.md") should include(
        "Ein Ding.",
      )
      files(sv)("classes/Thing.md") should include("A thing.")
    }
  }

  "DocsGenerator.serialize" should {
    "write all pages as sections of one document, linked with anchors" in {
      given SchemaView = ModelCatalogue.inheritance.model
      val result = DocsGenerator().serialize()
      result should startWith("<!-- Generated by LinkML-Scala from ")
      result should include("# inheritance\n")
      result should include("- **Tree root:** [ChildClass](#class-childclass)\n")
      result should include(
        """<a id="class-childclass"></a>
          |
          |## Class: ChildClass
          |""".stripMargin,
      )
      result should include("### Slots\n")
      result should include("- **Parent:** [BaseClass](#class-baseclass)\n")
      result should include("[some_other_slot](#slot-some_other_slot)")
      // Only the first line is the header: the sections do not repeat it.
      "Generated by LinkML-Scala".r.findAllMatchIn(result).size shouldBe 1
    }
  }

  "DocsGenerator.generateFiles with singleFile" should {
    "give one document, as serialize does" in {
      given SchemaView = ModelCatalogue.inheritance.model
      val options = DocsGenerator.Options(singleFile = true)
      DocsGenerator().generateFiles(options) shouldBe Seq(
        ("docs.md", DocsGenerator().serialize(options)),
      )
    }
  }
}
