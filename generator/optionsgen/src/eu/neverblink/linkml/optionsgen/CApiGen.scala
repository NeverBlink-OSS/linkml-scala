package eu.neverblink.linkml.optionsgen

/** Generates the generator and importer entry points of the C ABI from the functions of the options
  * schema.
  */
object CApiGen {

  def apply(schema: OptionsSchema): String = {
    val methods = schema.functions.map(render)

    s"""// Generated by generator/optionsgen from model/converter/all_converters.yaml
       |// DO NOT EDIT.
       |package eu.neverblink.linkml.nativelib
       |
       |import scala.scalanative.unsafe.*
       |
       |/** The generator and importer entry points of the C ABI, one per generator and importer.
       |  *
       |  * A generator takes a schema handle, an importer the document to import. Both then take an
       |  * options JSON that may be NULL for defaults, and an error out-param. The options follow
       |  * `model/converter`. They return the generated document, or NULL with `*error` set. Release
       |  * returned strings with `linkml_free`.
       |  *
       |  * See [[LinkMlCApi]] for loading, linting and the lifecycle.
       |  */
       |object LinkMlCGenerators {
       |
       |${methods.mkString("\n")}}
       |""".stripMargin
  }

  private def render(function: ConverterFunction): String = {
    val fields = function.options.fields
    val listed =
      if fields.isEmpty then "Takes no options."
      else "Options: " + fields.map(field => s"`${field.name}`").mkString(", ") + "."
    val json = if function.returns == Returns.Document then "" else " Returns JSON."
    val (input, helper) =
      if function.isImporter then ("document: CString", "imported")
      else ("handle: CLongLong", "document")

    s"""  /** ${function.description}$json $listed */
       |  @exported("${function.symbol}")
       |  def ${function.scalaName}($input, options: CString, error: Ptr[CString]): CString =
       |    LinkMlCApi.$helper(${input.takeWhile(
        _ != ':',
      )}, options, error, LinkMlNativeApi.${function.scalaName})
       |""".stripMargin
  }
}
