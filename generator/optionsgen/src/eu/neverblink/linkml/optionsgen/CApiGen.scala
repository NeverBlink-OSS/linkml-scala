package eu.neverblink.linkml.optionsgen

/** Generates the generator entry points of the C ABI from [[Entrypoints]]. */
object CApiGen {

  def apply(schema: OptionsSchema): String = {
    val methods = Entrypoints.all.map(entry => render(entry, schema.options(entry.generator)))

    s"""// Generated by generator/optionsgen from model/generator-options.yaml
       |// DO NOT EDIT.
       |package eu.neverblink.linkml.nativelib
       |
       |import scala.scalanative.unsafe.*
       |
       |/** The generator entry points of the C ABI, one per generator.
       |  *
       |  * All of them have the same shape: a schema handle, an options JSON that may be NULL for
       |  * defaults, and an error out-param. The options follow `model/generator-options.yaml`. They
       |  * return the generated document, or NULL with `*error` set. Release returned strings with
       |  * `linkml_free`.
       |  *
       |  * See [[LinkMlCApi]] for loading, linting and the lifecycle.
       |  */
       |object LinkMlCGenerators {
       |
       |${methods.mkString("\n")}}
       |""".stripMargin
  }

  private def render(entry: Entrypoints.Entrypoint, options: OptionsClass): String = {
    val listed =
      if options.fields.isEmpty then "Takes no options."
      else "Options: " + options.fields.map(field => s"`${field.name}`").mkString(", ") + "."
    val method = entry.python.split('_').toList match {
      case head :: tail => head + tail.map(_.capitalize).mkString
      case Nil => entry.python
    }

    s"""  /** ${entry.cComment} $listed */
       |  @exported("${entry.symbol}")
       |  def $method(handle: CLongLong, options: CString, error: Ptr[CString]): CString =
       |    LinkMlCApi.document(handle, options, error, LinkMlNativeApi.${entry.scalaMethod})
       |""".stripMargin
  }
}
