package eu.neverblink.linkml.optionsgen

/** Generates the generator entry points of the C ABI from the functions of the options schema. */
object CApiGen {

  def apply(schema: OptionsSchema): String = {
    val methods = schema.functions.map(render)

    s"""// Generated by generator/optionsgen from model/converter/all_generators.yaml
       |// DO NOT EDIT.
       |package eu.neverblink.linkml.nativelib
       |
       |import scala.scalanative.unsafe.*
       |
       |/** The generator entry points of the C ABI, one per generator.
       |  *
       |  * All of them have the same shape: a schema handle, an options JSON that may be NULL for
       |  * defaults, and an error out-param. The options follow
       |  * `model/converter/all_generators.yaml`. They return the generated document, or NULL with
       |  * `*error` set. Release returned strings with `linkml_free`.
       |  *
       |  * See [[LinkMlCApi]] for loading, linting and the lifecycle.
       |  */
       |object LinkMlCGenerators {
       |
       |${methods.mkString("\n")}}
       |""".stripMargin
  }

  private def render(function: GeneratorFunction): String = {
    val fields = function.options.fields
    val listed =
      if fields.isEmpty then "Takes no options."
      else "Options: " + fields.map(field => s"`${field.name}`").mkString(", ") + "."
    val json = if function.returns.isDefined then " Returns JSON." else ""

    s"""  /** ${function.description}$json $listed */
       |  @exported("${function.symbol}")
       |  def ${function.scalaName}(handle: CLongLong, options: CString, error: Ptr[CString]): CString =
       |    LinkMlCApi.document(handle, options, error, LinkMlNativeApi.${function.scalaName})
       |""".stripMargin
  }
}
