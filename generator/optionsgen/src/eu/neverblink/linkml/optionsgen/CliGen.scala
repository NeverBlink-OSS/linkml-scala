package eu.neverblink.linkml.optionsgen

/** The command line options of each generator and importer, for case-app, with the conversion to
  * its own options.
  *
  * The command classes of the CLI include these with `@Recurse`, next to the options that only the
  * command line has, such as `--to`.
  */
object CliGen {
  val pkg = "eu.neverblink.linkml.cli.options"

  private val header =
    s"""// Generated by generator/optionsgen from model/converter/all_converters.yaml
       |// DO NOT EDIT.
       |
       |package $pkg
       |""".stripMargin

  /** File name and content of each generated source. */
  def apply(schema: OptionsSchema): Seq[(String, String)] =
    schema.functions.map(f => s"${className(f)}.scala" -> options(f)) :+
      ("EnumParsers.scala" -> enumParsers(schema))

  /** `OwlCliOptions` for the `owl` generator, `FromOwlCliOptions` for the `from_owl` importer. */
  private def className(function: ConverterFunction): String =
    val base =
      function.options.scalaName.stripSuffix("GeneratorOptions").stripSuffix("ImporterOptions")
    if function.isImporter then s"From${base}CliOptions" else s"${base}CliOptions"

  private def options(function: ConverterFunction): String = {
    val c = function.options
    val name = className(function)
    val options = c.fields.filterNot(f => f.multivalued && f.valueClass.isDefined)
    val fields = options.map { f =>
      val default = f.default.fold("")(d => s" Default: ${d.text}")
      if f.valueClass.isDefined then
        val help = Literals.string(s"${f.description} The path to a YAML or JSON file with it.")
        s"""    @HelpMessage($help)
           |    ${f.scalaName}: Option[String] = None,""".stripMargin
      else
        val help = Literals.string(f.description + default)
        s"""    @HelpMessage($help)
           |    ${f.scalaName}: ${f.scalaType}${f.scalaDefault.fold("")(
            " = ".concat,
          )},""".stripMargin
    }
    val conversion = options.map { f =>
      val value =
        if f.valueClass.isEmpty then f.scalaName
        else s"${f.scalaName}.map(OptionFiles.read(_, LinkmlYamlCodec.derived[${f.valueType}]))"
      s"      ${f.scalaName} = $value,"
    }
    val readsFiles = options.exists(_.valueClass.isDefined)
    val imports = Seq(
      Option.when(readsFiles)("eu.neverblink.linkml.cli.files.OptionFiles"),
      Option.when(options.exists(_.isEnum))(s"$pkg.EnumParsers.given"),
      Some("eu.neverblink.linkml.generator.options.*"),
      Option.when(readsFiles)("eu.neverblink.linkml.yaml.LinkmlYamlCodec"),
    ).flatten.map("import ".concat).mkString("\n")

    s"""$header
       |import caseapp.*
       |$imports
       |
       |/** The command line options of [[${c.scalaName}]]. */
       |final case class $name(
       |${fields.mkString("\n")}
       |) {
       |
       |  /** The same options, for the ${
        if function.isImporter then "importer" else "generator"
      }. */
       |  def toOptions: ${c.scalaName} =
       |    ${c.scalaName}(
       |${conversion.mkString("\n")}
       |    )
       |}
       |
       |object $name {
       |  given Parser[$name] = Parser.derive
       |  given Help[$name] = Help.derive
       |}
       |""".stripMargin
  }

  private def enumParsers(schema: OptionsSchema): String = {
    val parsers = schema.enums.map { ev =>
      val name = schema.enumName(ev)
      val cases = schema.enumCases(ev).map { c =>
        val names = (c.name +: c.aliases).map(Literals.string).mkString(", ")
        s"      ${c.scalaCase} -> Seq($names),"
      }
      s"""  given ArgParser[$name] = parser(
         |    ${Literals.string(name.replaceAll("([a-z])([A-Z])", "$1 $2").toLowerCase)},
         |    Seq(
         |${cases.mkString("\n")}
         |    ),
         |  )""".stripMargin
    }

    s"""$header
       |import caseapp.core.Error
       |import caseapp.core.argparser.{ArgParser, SimpleArgParser}
       |import eu.neverblink.linkml.generator.options.*
       |
       |/** Parses the values of the enums in the options. A value matches its name or one of its
       |  * aliases, ignoring case, `-` and `_`, so `tree_root`, `tree-root` and `treeRoot` are the same.
       |  */
       |object EnumParsers {
       |
       |${parsers.mkString("\n\n")}
       |
       |  private def parser[E](what: String, cases: Seq[(E, Seq[String])]): ArgParser[E] = {
       |    val names = cases.map(_._2.head)
       |    SimpleArgParser.from(names.mkString("|")) { value =>
       |      cases
       |        .collectFirst { case (e, spellings) if spellings.exists(same(_, value)) => e }
       |        .toRight(Error.MalformedValue(what, s"$$value (expected one of: $${names.mkString(", ")})"))
       |    }
       |  }
       |
       |  private def same(a: String, b: String): Boolean = normalize(a) == normalize(b)
       |
       |  private def normalize(s: String): String = s.filter(c => c != '-' && c != '_').toLowerCase
       |}
       |""".stripMargin
  }
}
