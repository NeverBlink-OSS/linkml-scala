package eu.neverblink.linkml.optionsgen

/** The command line options of each generator, for case-app, with the conversion to the generator's
  * own options.
  *
  * The command classes of the CLI include these with `@Recurse`, next to the options that only the
  * command line has, such as `--to`.
  */
object CliGen {
  val pkg = "eu.neverblink.linkml.cli.options"

  private val header =
    s"""// Generated by generator/optionsgen from model/generator-options.yaml
       |// DO NOT EDIT.
       |
       |package $pkg
       |""".stripMargin

  /** File name and content of each generated source. */
  def apply(schema: OptionsSchema): Seq[(String, String)] =
    schema.generators.map(c => s"${c.baseName}CliOptions.scala" -> options(c)) :+
      ("EnumParsers.scala" -> enumParsers(schema))

  private def options(c: OptionsClass): String = {
    val name = s"${c.baseName}CliOptions"
    val fields = c.fields.map { f =>
      val default = f.default.fold("")(d => s" Default: ${d.text}")
      val help = Literals.string(f.description + default)
      s"""    @HelpMessage($help)
         |    ${f.scalaName}: ${f.scalaType}${f.scalaDefault.fold("")(" = ".concat)},""".stripMargin
    }
    val conversion = c.fields.map(f => s"      ${f.scalaName} = ${f.scalaName},")
    val enumParsers =
      if c.fields.exists(_.isEnum) then s"import $pkg.EnumParsers.given\n" else ""

    s"""$header
       |import caseapp.*
       |${enumParsers}import eu.neverblink.linkml.generator.options.*
       |
       |/** The command line options of [[${c.scalaName}]]. */
       |final case class $name(
       |${fields.mkString("\n")}
       |) {
       |
       |  /** The same options, for the generator. */
       |  def toGeneratorOptions: ${c.scalaName} =
       |    ${c.scalaName}(
       |${conversion.mkString("\n")}
       |    )
       |}
       |
       |object $name {
       |  given Parser[$name] = Parser.derive
       |  given Help[$name] = Help.derive
       |}
       |""".stripMargin
  }

  private def enumParsers(schema: OptionsSchema): String = {
    val parsers = schema.enums.map { ev =>
      val name = schema.enumName(ev)
      val cases = schema.enumCases(ev).map { c =>
        val names = (c.name +: c.aliases).map(Literals.string).mkString(", ")
        s"      ${c.scalaCase} -> Seq($names),"
      }
      s"""  given ArgParser[$name] = parser(
         |    ${Literals.string(name.replaceAll("([a-z])([A-Z])", "$1 $2").toLowerCase)},
         |    Seq(
         |${cases.mkString("\n")}
         |    ),
         |  )""".stripMargin
    }

    s"""$header
       |import caseapp.core.Error
       |import caseapp.core.argparser.{ArgParser, SimpleArgParser}
       |import eu.neverblink.linkml.generator.options.*
       |
       |/** Parses the values of the enums in the options. A value matches its name or one of its
       |  * aliases, ignoring case, `-` and `_`, so `tree_root`, `tree-root` and `treeRoot` are the same.
       |  */
       |object EnumParsers {
       |
       |${parsers.mkString("\n\n")}
       |
       |  private def parser[E](what: String, cases: Seq[(E, Seq[String])]): ArgParser[E] = {
       |    val names = cases.map(_._2.head)
       |    SimpleArgParser.from(names.mkString("|")) { value =>
       |      cases
       |        .collectFirst { case (e, spellings) if spellings.exists(same(_, value)) => e }
       |        .toRight(Error.MalformedValue(what, s"$$value (expected one of: $${names.mkString(", ")})"))
       |    }
       |  }
       |
       |  private def same(a: String, b: String): Boolean = normalize(a) == normalize(b)
       |
       |  private def normalize(s: String): String = s.filter(c => c != '-' && c != '_').toLowerCase
       |}
       |""".stripMargin
  }
}
