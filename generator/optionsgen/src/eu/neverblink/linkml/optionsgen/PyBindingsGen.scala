package eu.neverblink.linkml.optionsgen

import eu.neverblink.linkml.schemaview.{BooleanType, IntegerType, RuntimeType}

/** Generates the Python bindings' generator methods from the functions of the options schema, so
  * the option names, types, defaults and docs can never drift from the generators.
  */
object PyBindingsGen {

  def apply(schema: OptionsSchema): String = {
    val methods = schema.functions.map(render)
    val symbols = schema.functions.map(f => s"""    "${f.symbol}",""").mkString("\n")
    val literal = schema.enums.nonEmpty

    s"""# Generated by generator/optionsgen from model/converter/all_generators.yaml
       |# DO NOT EDIT.
       |\"\"\"The generator methods of :class:`ohi_linkml.Schema`.
       |
       |The keyword arguments, their defaults and their documentation follow
       |``model/converter/all_generators.yaml``, the options every binding of the generators shares.
       |\"\"\"
       |
       |from __future__ import annotations
       |
       |from typing import Any${
        if literal then ", Literal" else ""
      }
       |
       |# Every exported function taking (handle, options) and returning a document or NULL.
       |DOCUMENT_FUNCTIONS = (
       |$symbols
       |)
       |
       |
       |class Generators:
       |    \"\"\"Mixin holding one method per generator. Mixed into :class:`ohi_linkml.Schema`.\"\"\"
       |
       |${methods.mkString("\n")}""".stripMargin
  }

  private def render(function: GeneratorFunction): String = {
    val params = function.options.fields
    val returns = function.returns match {
      case None => "str"
      case Some(Some(tv)) => s"dict[str, ${typeName(tv.runtimeType)}]"
      case Some(None) => "Any"
    }

    val signature =
      if params.isEmpty then s"    def ${function.name}(self) -> $returns:"
      else {
        val rendered =
          params.map(p => s"        ${p.name}: ${pythonType(p)} = ${pythonDefault(p)},")
        s"""    def ${function.name}(
           |        self,
           |        *,
           |${rendered.mkString("\n")}
           |    ) -> $returns:""".stripMargin
      }

    val doc = {
      val summary = wrap(function.description, "        \"\"\"", "        ")
      val lines = params.filter(_.description.nonEmpty)
        .map(p => wrap(s":param ${p.name}: ${p.description}", "        ", "            "))
      if lines.isEmpty then s"$summary\"\"\""
      else s"$summary\n\n${lines.mkString("\n")}\n        \"\"\""
    }

    val method = if function.returns.isDefined then "_json" else "_document"
    val body =
      if params.isEmpty then s"""        return self.$method("${function.symbol}")"""
      else s"""        return self.$method(
           |            "${function.symbol}",
           |${params.map(p => s"            ${p.name}=${p.name},").mkString("\n")}
           |        )""".stripMargin

    s"$signature\n$doc\n$body\n"
  }

  private def pythonType(field: OptionField): String = {
    val value = field.enumValues match {
      case Some(values) => values.map(v => s"\"$v\"").mkString("Literal[", ", ", "]")
      case None =>
        field.valueType match {
          case "Boolean" => "bool"
          case "Int" => "int"
          case _ => "str"
        }
    }
    if field.required then value else s"$value | None"
  }

  private def pythonDefault(field: OptionField): String =
    field.default match {
      case None => "None"
      case Some(d) =>
        field.valueType match {
          case "Boolean" => d.text.capitalize
          case "Int" => d.text
          case _ => "\"" + d.text.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
        }
    }

  private def typeName(tpe: RuntimeType): String = tpe match {
    case BooleanType => "bool"
    case IntegerType => "int"
    case _ => "str"
  }

  /** Wrap a docstring line to stay inside the project's line length.
    *
    * @param first
    *   what the first line starts with
    * @param rest
    *   what the other lines start with
    */
  private def wrap(line: String, first: String, rest: String): String = {
    val limit = 96
    val out = List.newBuilder[String]
    val current = new StringBuilder(first)
    var empty = true
    line.split(' ').foreach { word =>
      if current.length + 1 + word.length > limit && !empty then {
        out += current.toString
        current.clear()
        current.append(rest)
        empty = true
      }
      if !empty then current.append(' ')
      current.append(word)
      empty = false
    }
    out += current.toString.stripTrailing()
    out.result().mkString("\n")
  }
}
