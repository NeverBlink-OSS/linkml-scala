package eu.neverblink.linkml.optionsgen

import eu.neverblink.linkml.schemaview.{BooleanType, IntegerType, RuntimeType}

/** Generates the Python bindings' generator methods and importer functions from the functions of
  * the options schema, so the option names, types, defaults and docs can never drift from the
  * generators and importers.
  */
object PyBindingsGen {

  def apply(schema: OptionsSchema): String = {
    val (importers, generators) = schema.functions.partition(_.isImporter)
    def symbols(functions: Seq[ConverterFunction]) =
      functions.map(f => s"""    "${f.symbol}",""").mkString("\n")
    val literal = schema.enums.nonEmpty

    s"""# Generated by generator/optionsgen from model/converter/all_converters.yaml
       |# DO NOT EDIT.
       |\"\"\"The generator methods of :class:`ohi_linkml.Schema`, and the importers.
       |
       |The keyword arguments, their defaults and their documentation follow
       |``model/converter``, the options every binding of the generators and importers shares.
       |\"\"\"
       |
       |from __future__ import annotations
       |
       |import json
       |from typing import Any${if literal then ", Literal" else ""}
       |
       |from ._runtime import runtime
       |
       |# Every exported function taking (handle, options) and returning a document or NULL.
       |DOCUMENT_FUNCTIONS = (
       |${symbols(generators)}
       |)
       |
       |# Every exported function taking (document, options) and returning a document or NULL.
       |IMPORT_FUNCTIONS = (
       |${symbols(importers)}
       |)
       |
       |
       |class Generators:
       |    \"\"\"Mixin holding one method per generator. Mixed into :class:`ohi_linkml.Schema`.\"\"\"
       |
       |${generators.map(renderGenerator).mkString("\n")}
       |${importers.map(renderImporter).mkString("\n\n")}""".stripMargin
  }

  private def renderGenerator(function: ConverterFunction): String = {
    val params = function.options.fields
    val first = if params.isEmpty then Seq("self") else Seq("self", "*")
    val signature = this.signature("    ", function, first)
    val method = if function.returns == Returns.Document then "_document" else "_json"
    val body = call(s"self.$method", Seq(quoted(function.symbol)), params)
    s"$signature\n${doc("        ", function, Nil)}\n$body\n"
  }

  private def renderImporter(function: ConverterFunction): String = {
    val params = function.options.fields
    val signature =
      this.signature("", function, Seq("document: str") ++ Option.when(params.nonEmpty)("*"))
    val document = ":param document: The document to import."
    val options =
      if params.isEmpty then "    options = None"
      else
        params.map(p => s"        ${quoted(p.name)}: ${p.name},").mkString(
          "    options = {\n",
          "\n",
          "\n    }",
        )
    val imported = s"runtime().import_document(${quoted(function.symbol)}, document, options)"
    val body =
      if function.returns == Returns.Document then s"    return $imported"
      else s"    return json.loads($imported)"
    s"\n$signature\n${doc("    ", function, Seq(document))}\n$options\n$body"
  }

  /** The `def` line, with each parameter on its own line if there are options. */
  private def signature(indent: String, function: ConverterFunction, first: Seq[String]): String = {
    val params = function.options.fields
    val returns = function.returns match {
      case Returns.Document => "str"
      case Returns.Map(tv) => s"dict[str, ${typeName(tv.runtimeType)}]"
      case Returns.Object => "dict[str, Any]"
      case Returns.Any => "Any"
    }
    if params.isEmpty then s"${indent}def ${function.name}(${first.mkString(", ")}) -> $returns:"
    else {
      val rendered = first.map(p => s"$indent    $p,") ++
        params.map(p => s"$indent    ${p.name}: ${pythonType(p)} = ${pythonDefault(p)},")
      s"""${indent}def ${function.name}(
         |${rendered.mkString("\n")}
         |$indent) -> $returns:""".stripMargin
    }
  }

  private def doc(indent: String, function: ConverterFunction, first: Seq[String]): String = {
    val summary = wrap(function.description, indent + "\"\"\"", indent)
    val lines = (first ++ function.options.fields.filter(_.description.nonEmpty)
      .map(p => s":param ${p.name}: ${p.description}"))
      .map(wrap(_, indent, indent + "    "))
    if lines.isEmpty then s"$summary\"\"\""
    else s"$summary\n\n${lines.mkString("\n")}\n$indent\"\"\""
  }

  /** A call of a generator method, with each option passed on by keyword. */
  private def call(method: String, first: Seq[String], params: Seq[OptionField]): String =
    if params.isEmpty then s"        return $method(${first.mkString(", ")})"
    else
      s"""        return $method(
         |${(first ++ params.map(p => s"${p.name}=${p.name}")).map(a =>
          s"            $a,",
        ).mkString("\n")}
         |        )""".stripMargin

  private def quoted(text: String): String = s"\"$text\""

  private def pythonType(field: OptionField): String = {
    val value = field.enumValues match {
      case Some(values) => values.map(v => s"\"$v\"").mkString("Literal[", ", ", "]")
      case None if field.valueClass.isDefined => "dict[str, Any]"
      case None =>
        field.valueType match {
          case "Boolean" => "bool"
          case "Int" => "int"
          case _ => "str"
        }
    }
    if field.required then value else s"$value | None"
  }

  private def pythonDefault(field: OptionField): String =
    field.default match {
      case None => "None"
      case Some(d) =>
        field.valueType match {
          case "Boolean" => d.text.capitalize
          case "Int" => d.text
          case _ => "\"" + d.text.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
        }
    }

  private def typeName(tpe: RuntimeType): String = tpe match {
    case BooleanType => "bool"
    case IntegerType => "int"
    case _ => "str"
  }

  /** Wrap a docstring line to stay inside the project's line length.
    *
    * @param first
    *   what the first line starts with
    * @param rest
    *   what the other lines start with
    */
  private def wrap(line: String, first: String, rest: String): String = {
    val limit = 96
    val out = List.newBuilder[String]
    val current = new StringBuilder(first)
    var empty = true
    line.split(' ').foreach { word =>
      if current.length + 1 + word.length > limit && !empty then {
        out += current.toString
        current.clear()
        current.append(rest)
        empty = true
      }
      if !empty then current.append(' ')
      current.append(word)
      empty = false
    }
    out += current.toString.stripTrailing()
    out.result().mkString("\n")
  }
}
