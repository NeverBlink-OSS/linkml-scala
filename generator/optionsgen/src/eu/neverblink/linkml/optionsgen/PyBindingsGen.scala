package eu.neverblink.linkml.optionsgen

/** Generates the Python bindings' generator methods from [[Entrypoints]] and the options schema, so
  * the option names, types, defaults and docs can never drift from the generators.
  */
object PyBindingsGen {

  def apply(schema: OptionsSchema): String = {
    val methods = Entrypoints.all.map(entry => render(entry, schema.options(entry.generator)))
    val symbols = Entrypoints.all.map(e => s"""    "${e.symbol}",""").mkString("\n")
    val literal = schema.enums.nonEmpty

    s"""# Generated by generator/optionsgen from model/generator-options.yaml
       |# DO NOT EDIT.
       |\"\"\"The generator methods of :class:`linkml_scala.Schema`.
       |
       |The keyword arguments, their defaults and their documentation follow
       |``model/generator-options.yaml``, the options every binding of the generators shares.
       |\"\"\"
       |
       |from __future__ import annotations
       |
       |from typing import Any${
        if literal then ", Literal" else ""
      }
       |
       |# Every exported function taking (handle, options) and returning a document or NULL.
       |DOCUMENT_FUNCTIONS = (
       |$symbols
       |)
       |
       |
       |class Generators:
       |    \"\"\"Mixin holding one method per generator. Mixed into :class:`linkml_scala.Schema`.\"\"\"
       |
       |${methods.mkString("\n")}""".stripMargin
  }

  private def render(entry: Entrypoints.Entrypoint, options: OptionsClass): String = {
    val params = options.fields

    val signature =
      if params.isEmpty then s"    def ${entry.python}(self) -> ${entry.returns}:"
      else {
        val rendered =
          params.map(p => s"        ${p.name}: ${pythonType(p)} = ${pythonDefault(p)},")
        s"""    def ${entry.python}(
           |        self,
           |        *,
           |${rendered.mkString("\n")}
           |    ) -> ${entry.returns}:""".stripMargin
      }

    val doc = {
      val lines =
        params.filter(_.description.nonEmpty).map(p => wrap(s":param ${p.name}: ${p.description}"))
      if lines.isEmpty then s"""        \"\"\"${entry.summary}\"\"\""""
      else s"""        \"\"\"${entry.summary}
           |
           |${lines.mkString("\n")}
           |        \"\"\"""".stripMargin
    }

    val method = if entry.structured then "_json" else "_document"
    val body =
      if params.isEmpty then s"""        return self.$method("${entry.symbol}")"""
      else s"""        return self.$method(
           |            "${entry.symbol}",
           |${params.map(p => s"            ${p.name}=${p.name},").mkString("\n")}
           |        )""".stripMargin

    s"$signature\n$doc\n$body\n"
  }

  private def pythonType(field: OptionField): String = {
    val value = field.enumValues match {
      case Some(values) => values.map(v => s"\"$v\"").mkString("Literal[", ", ", "]")
      case None =>
        field.valueType match {
          case "Boolean" => "bool"
          case "Int" => "int"
          case _ => "str"
        }
    }
    if field.required then value else s"$value | None"
  }

  private def pythonDefault(field: OptionField): String =
    field.default match {
      case None => "None"
      case Some(d) =>
        field.valueType match {
          case "Boolean" => d.text.capitalize
          case "Int" => d.text
          case _ => "\"" + d.text.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
        }
    }

  /** Wrap a `:param:` line to stay inside the project's line length, indenting continuations the
    * way the hand-written docstrings do.
    */
  private def wrap(line: String): String = {
    val limit = 96
    val words = line.split(' ')
    val out = List.newBuilder[String]
    val current = new StringBuilder("        ")
    words.foreach { word =>
      if current.length + 1 + word.length > limit && current.toString.trim.nonEmpty then {
        out += current.toString.stripTrailing()
        current.clear()
        current.append("            ")
      }
      if current.toString.trim.nonEmpty then current.append(' ')
      current.append(word)
    }
    out += current.toString.stripTrailing()
    out.result().mkString("\n")
  }
}
