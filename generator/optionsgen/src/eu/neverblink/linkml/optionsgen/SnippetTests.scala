package eu.neverblink.linkml.optionsgen

/** Tests that run the examples of [[Snippets]], in a directory with the files of
  * `model/converter/examples`.
  */
object SnippetTests {

  private def snippets(schema: OptionsSchema, sdk: Sdk): Seq[(ConverterFunction, Snippet)] =
    schema.functions.map(f => f -> Snippets(f, schema).find(_.sdk == sdk).get)

  private def indent(code: String, margin: String): String =
    code.linesIterator.map(l => if l.isEmpty then l else margin + l).mkString("\n")

  /** `python/test_snippets.py`, which `./mill nativelib.native.pythonTest` runs. */
  def python(schema: OptionsSchema): String = {
    val tests = snippets(schema, Sdk.Python).map { (f, s) =>
      val check = if f.isImporter then s"""${s.result}["schema"]""" else s.result
      s"""    def test_${f.name}(self) -> None:
         |${indent(s.code, "        ")}
         |        self.assertTrue($check)
         |""".stripMargin
    }
    s"""# Generated by generator/optionsgen from model/converter/all_converters.yaml
       |# DO NOT EDIT.
       |\"\"\"Runs the Python examples on the generator and importer pages of the docs.\"\"\"
       |
       |from __future__ import annotations
       |
       |import os
       |import shutil
       |import tempfile
       |import unittest
       |from pathlib import Path
       |
       |REPO_ROOT = Path(os.environ.get("LINKML_SCALA_REPO") or Path(__file__).resolve().parents[1])
       |EXAMPLES = REPO_ROOT / "model" / "converter" / "examples"
       |
       |
       |class DocSnippetsTest(unittest.TestCase):
       |    def setUp(self) -> None:
       |        self._cwd = os.getcwd()
       |        self._dir = tempfile.TemporaryDirectory()
       |        for example in EXAMPLES.iterdir():
       |            shutil.copy(example, self._dir.name)
       |        os.chdir(self._dir.name)
       |
       |    def tearDown(self) -> None:
       |        os.chdir(self._cwd)
       |        self._dir.cleanup()
       |
       |${tests.mkString("\n")}""".stripMargin
  }

  /** `generator/npm/snippets.test.mjs`, which `verify-package.mjs` runs and type-checks. */
  def javaScript(schema: OptionsSchema): String = {
    val all = snippets(schema, Sdk.JavaScript)
    val tests = all.map { (f, s) =>
      val check = if f.isImporter then s"${s.result}.schema" else s.result
      s"""// ${f.name}
         |{
         |${indent(s.body, "  ")}
         |  if (!$check) throw new Error("${f.name} gave nothing");
         |}
         |""".stripMargin
    }
    s"""// Generated by generator/optionsgen from model/converter/all_converters.yaml
       |// DO NOT EDIT.
       |// Runs the JavaScript examples on the generator and importer pages of the docs.
       |
       |${all.flatMap(_._2.imports).distinct.mkString("\n")}
       |
       |${tests.mkString("\n")}""".stripMargin
  }

  /** `cli/test/src/eu/neverblink/linkml/cli/DocSnippetsSpec.scala`, for the command line and Scala
    * examples.
    */
  def scala(schema: OptionsSchema): String = {
    val cli = snippets(schema, Sdk.Cli).toMap
    val tests = snippets(schema, Sdk.Scala).map { (f, s) =>
      val command = cli(f).body.linesIterator.drop(1).map(_.stripSuffix(" \\").trim)
        .mkString(" ").stripPrefix("ohi linkml ")
      val check = f.returns match {
        case Returns.Object | Returns.Any if !f.isImporter => s"${s.result} != null"
        case _ => s"${s.result}.nonEmpty"
      }
      s"""  "the ${f.name} examples" should {
         |    "run on the command line" in {
         |      ohiLinkml(${Code.quoted(command)})
         |    }
         |    "run in Scala" in {
         |${indent(s.code, "      ")}
         |      assert($check)
         |    }
         |  }
         |""".stripMargin
    }
    s"""// Generated by generator/optionsgen from model/converter/all_converters.yaml
       |// DO NOT EDIT.
       |
       |package eu.neverblink.linkml.cli
       |
       |import org.scalatest.wordspec.AnyWordSpec
       |
       |import java.io.{ByteArrayOutputStream, PrintStream}
       |
       |/** Runs the command line and Scala examples on the generator and importer pages of the docs, in
       |  * the working directory, with the files of `model/converter/examples`.
       |  */
       |class DocSnippetsSpec extends AnyWordSpec {
       |
       |  os.list(os.Path(sys.env("MILL_WORKSPACE_ROOT")) / "model" / "converter" / "examples")
       |    .foreach(os.copy.into(_, os.pwd, replaceExisting = true))
       |
       |  /** Run the command after `ohi linkml`, which is `generate` here instead of `to`. */
       |  private def ohiLinkml(command: String): Unit = {
       |    val args = command.split(' ').toList match {
       |      case "to" :: rest => "generate" :: rest
       |      case other => other
       |    }
       |    val out = ByteArrayOutputStream()
       |    val err = ByteArrayOutputStream()
       |    val code =
       |      try {
       |        App(testMode = true, PrintStream(out, true, "UTF-8"), PrintStream(err, true, "UTF-8"))
       |          .main(args.toArray)
       |        0
       |      } catch { case ExitException(code) => code }
       |    assert(code == 0, err.toString("UTF-8"))
       |  }
       |
       |${tests.mkString("\n")}}
       |""".stripMargin
  }
}
