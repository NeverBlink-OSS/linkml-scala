package eu.neverblink.linkml.agents

import eu.neverblink.linkml.agents.Yaml.*
import eu.neverblink.linkml.metamodel.Resources
import org.virtuslab.yaml.Node

import scala.collection.immutable.ListMap
import scala.collection.mutable
import scala.math.Ordering.Implicits.seqOrdering

/** The derived files of the `linkml` agent skill, so it cannot drift from the implementation it
  * describes. Sources:
  *
  *   - the LinkML metamodel bundled with the `metamodel` module;
  *   - guides from `website/src/content/docs/`, published at https://linkml.ohi.dev/docs/;
  *   - the example schemas in `tests/resources/models/`.
  *
  * Deliberately not generated: a CLI reference, or a catalogue of validator issues. The CLI's
  * `--help` and its validation messages are self-describing, so a bundled copy would only rot.
  *
  * Run with `./mill agents.generate`. The `agents.test` tests fail when the files are stale.
  */
object SkillFiles {

  /** Writes the files that changed. The only argument is the repository root. */
  def main(args: Array[String]): Unit = {
    val repo = os.Path(args(0))
    for (name, content) <- generate(repo) do
      val target = skillDir(repo) / name
      if !os.isFile(target) || os.read(target) != content then
        os.write.over(target, content)
        println(s"wrote ${target.relativeTo(repo)} (${content.length} chars)")
  }

  def skillDir(repo: os.Path): os.Path = repo / ".agents" / "skills" / "linkml"

  /** The content of each generated file, by its name in [[skillDir]]. */
  def generate(repo: os.Path): ListMap[String, String] = ListMap(
    "900-metaslots.tsv" -> metaslots,
    "200-limitations.md" -> (banner + source("implementation-differences") +
      "> **Read this before using any LinkML feature you have not used with linkml-scala\n" +
      "> before.** Everything under *Limitations* is ignored or rejected. The semantics\n" +
      "> sections diverge from linkml-python, so a schema can behave differently here.\n\n" +
      guide(repo, "implementation-differences")),
    "210-slot-usage-inheritance.md" -> copiedGuide(repo, "slot-usage-inheritance"),
    "220-import-maps.md" -> copiedGuide(repo, "import-maps"),
    "230-curies.md" -> copiedGuide(repo, "curies"),
    "240-langstring.md" -> copiedGuide(repo, "langstring"),
    "910-examples.md" -> examples(repo),
  )

  // The guides the skill has a copy of, and the skill files they are copied to
  private val guideFiles = ListMap(
    "implementation-differences" -> "200-limitations.md",
    "slot-usage-inheritance" -> "210-slot-usage-inheritance.md",
    "import-maps" -> "220-import-maps.md",
    "curies" -> "230-curies.md",
    "langstring" -> "240-langstring.md",
  )

  private val banner = "<!-- GENERATED by ./mill agents.generate - do not edit by hand. -->\n"

  // The metamodel ships several schemas. Only some describe the vocabulary you use when authoring:
  // datasets.yaml is a separate data-package model, array.yaml covers arrays (unsupported here),
  // and validation.yaml is the validation-report model.
  private val authoringSchemas =
    Seq("meta", "types", "mappings", "extensions", "annotations", "units")

  private val tiers = Map(
    "MinimalSubset" -> "min",
    "BasicSubset" -> "basic",
    "SpecificationSubset" -> "spec",
    "ObjectOrientedProfile" -> "oo",
    "RelationalModelProfile" -> "rel",
  )

  private def oneLine(text: Option[String], limit: Int = 90): String = {
    val flat = text.getOrElse("").trim.split("(?U)\\s+").mkString(" ")
    if flat.codePointCount(0, flat.length) <= limit then flat
    else flat.substring(0, flat.offsetByCodePoints(0, limit - 1)).stripTrailing() + "…"
  }

  /** A compact, greppable index of the authoring vocabulary.
    *
    * TSV rather than Markdown on purpose: this is queried with grep/awk, never read from start to
    * finish, and pipe-aligned tables would cost tokens for nothing.
    */
  private def metaslots: String = {
    val classes = mutable.LinkedHashMap.empty[String, Option[Node]]
    val slots = mutable.LinkedHashMap.empty[String, Option[Node]]
    for schema <- authoringSchemas; doc <- Yaml.load(Resources.read(s"/$schema.yaml")) do
      doc.get("classes").foreach(_.entries.foreach((k, v) => classes(k) = Some(v)))
      doc.get("slots").foreach(_.entries.foreach((k, v) => slots(k) = Some(v)))

    val owners = mutable.LinkedHashMap.empty[String, Vector[String]]
    for (cname, cdef) <- classes; slot <- cdef.flatMap(_.get("slots")).toSeq.flatMap(_.items)
    do slot.text.foreach(s => owners(s) = owners.getOrElse(s, Vector.empty) :+ cname)

    val rows = slots.toSeq.sortBy(_._1).map { (name, sdef) =>
      def field(key: String) = sdef.flatMap(_.get(key))
      val declared = owners.getOrElse(name, Vector.empty)
      val used =
        if declared.nonEmpty then declared else field("domain").flatMap(_.text).toVector
      val shown = if used.size > 3 then used.take(3) :+ s"+${declared.size - 3}" else used
      val card = (if field("multivalued").exists(_.isTrue) then "multi" else "single") +
        (if field("required").exists(_.isTrue) then ",required" else "")
      val slotTiers = field("in_subset").toSeq.flatMap(_.items).flatMap(_.text).flatMap(tiers.get)
      Seq(
        name,
        if shown.isEmpty then "-" else shown.mkString(","),
        field("range").flatMap(_.text).filter(_.nonEmpty).getOrElse("string"),
        card,
        if slotTiers.isEmpty then "-" else slotTiers.mkString(","),
        oneLine(field("description").flatMap(_.text)),
      ).mkString("\t")
    }

    s"""# GENERATED by ./mill agents.generate - do not edit by hand.
       |#
       |# The LinkML authoring vocabulary: every metamodel slot you may write in a schema,
       |# ${rows.size} of them. Query it, do not read it. Columns are tab-separated, so anchor
       |# on the column - a bare `grep basic` also matches every description with that word.
       |#
       |#   grep -P '^inlined\\t' 900-metaslots.tsv                              # one slot
       |#   awk -F'\\t' '$$5 ~ /min|basic/ {print $$1}' 900-metaslots.tsv          # everyday slots
       |#   awk -F'\\t' '$$2 ~ /class_definition/ {print $$1}' 900-metaslots.tsv  # what a class carries
       |#
       |# tier: min/basic = commonly used, spec = in the formal specification,
       |# oo/rel = object-oriented / relational profiles only.
       |#
       |# used_on lists only classes declaring a slot directly. Classes also inherit every
       |# slot of their is_a/mixins ancestors, so class_definition does accept name and
       |# description even though those are declared on element.
       |#
       |# Presence here means the *metamodel* defines it, NOT that linkml-scala implements
       |# it. Check 200-limitations.md before relying on anything unusual.
       |#
       |# slot\tused_on\trange\tcardinality\ttier\tdescription
       |""".stripMargin + rows.mkString("\n") + "\n"
  }

  /** A guide from the docs site as plain Markdown: its frontmatter title as a `# Title` line, and
    * its links to other pages pointing at their copies in the skill, or else at the site.
    */
  private def guide(repo: os.Path, slug: String): String = {
    val text = os.read(repo / "website" / "src" / "content" / "docs" / s"$slug.md")
    val Array(_, frontmatter, rest) = text.split("---\n", 3): @unchecked
    val title = Yaml.load(frontmatter).flatMap(_.get("title")).flatMap(_.text).getOrElse("")
    val body = guideFiles.foldLeft(rest) { case (text, (page, skillFile)) =>
      text.replace(s"](/docs/$page/#", s"]($skillFile#").replace(
        s"](/docs/$page/)",
        s"]($skillFile)",
      )
    }
    s"# $title\n" + body.replace("](/docs/", "](https://linkml.ohi.dev/docs/")
  }

  private def source(slug: String): String =
    s"<!-- Source: website/src/content/docs/$slug.md -->\n\n"

  private def copiedGuide(repo: os.Path, slug: String): String =
    banner + source(slug) + guide(repo, slug)

  private def examples(repo: os.Path): String = {
    val root = repo / "tests" / "resources" / "models"
    val models = os.walk(root).filter(_.last == "model.yaml").sortBy(_.segments.toSeq)
    val rows = for
      model <- models
      doc <- Yaml.parse(os.read(model)).toOption
    yield {
      // Only a real description earns a note. The class names in these test models are
      // placeholders (`SomeClass`, `SomeOtherClass`), so listing them told the reader nothing the
      // feature column had not already said.
      val note = oneLine(doc.flatMap(_.get("description")).flatMap(_.text), 60)
      def count(kind: String) = {
        val dir = model / os.up / kind
        if os.isDir(dir) then os.walk(dir).size else 0
      }
      s"| `${(model / os.up).relativeTo(root)}` | ${count("valid")} | ${count("invalid")} | $note |"
    }

    (Seq(
      banner,
      "# Known-good example schemas\n",
      "Dozens of schemas from the linkml-scala test suite. Each exercises one feature and is",
      "verified against every generator on every commit, so when you are unsure how something is",
      "written, read the matching `model.yaml` instead of guessing.\n",
      "Paths are relative to `tests/resources/models/`:",
      "<https://github.com/NeverBlink-OSS/linkml-scala/tree/main/tests/resources/models>\n",
      "`valid`/`invalid` count the instance-data files shipped with the schema — worked examples",
      "of what it does and does not accept, and the fastest way to sanity-check a data validator.\n",
      "| feature | valid | invalid | notes |",
      "|---|---|---|---|",
    ) ++ rows).mkString("\n") + "\n"
  }
}
